# src/evaluation.py

"""
Evaluation module for the Analogical Reasoning RAG project.
This file provides the core logic for assessing the performance of the generated
solutions.
Its responsibilities include:

1.  Evaluating a single generated answer against a ground truth using an LLM.
2.  Parsing and analyzing the detailed JSON logs from experiment runs to manage
    state and resume progress.
3.  Calculating Pass@K metrics and aggregating error statistics across all
    experiments.
4.  Generating a final summary DataFrame for analysis and reporting.
MODIFIED: This version is updated to support **Multi-Strategy Evaluation** for the
"Acquire-Optimize-Fork" architecture.
It iterates through:
1. The primary solution strategy (from `steps.solving`).
2. Track A Benchmarks (from `benchmarks`).
3. Track B Validations (from `steps_alternatives`).
It reports Pass@K metrics for *each* strategy independently in the final DataFrame.
"""

import hashlib
import logging
import os
import re
import pandas as pd
from tqdm import tqdm
from typing import List, Dict, Any, Tuple, Optional, TypedDict
from collections import defaultdict

from src.utils import save_json, load_json
from src.api_manager import APIResponse, model_name_for
from src.answer_bank import (
    PACKED_JUDGE, AnswerBank, JudgeCase, answer_bank_summary, build_case,
    get_answer_bank, parse_packed_reply, rule_verdict, same_answer,
)
from src.benchmark_data import benchmark_name_for_target_index, uses_exact_final_answers

# Pass@K attempts after the first correct one are not judged when
# EVAL_LAZY_PASS_AT_K is on; every Pass@K value stays the same.
LAZY_SKIP_STATUS = "SKIPPED_AFTER_CORRECT"

# Define a structured type for the result of a single LLM-based evaluation
class EvaluationResult(TypedDict):
    """The structured result of a single answer evaluation call.

    With the answer bank on, a successful result also carries ``judge_method``:
    ``bank``/``bank_text``/``bank_value`` (an earlier LLM verdict),
    ``exact``/``numeric`` (a rule), or ``llm``/``llm_packed``/``llm_joined``/
    ``audit`` (a judge call made for this or an identical answer).
    """
    is_correct: Optional[bool]
    status: str
    error_details: Optional[APIResponse]


def _extract_last_boxed_line(solution_text: str) -> Tuple[str, bool]:
    """
    Parses the solution text to find the last line containing a '\boxed{}' answer.
    If found, returns (line.strip(), True). Otherwise, returns (original_solution, False).
    """
    if not solution_text or not isinstance(solution_text, str):
        return solution_text, False
        
    lines = solution_text.split('\n')
    # Search backwards to find the LAST occurrence of 'boxed'
    for line in reversed(lines):
        if 'boxed' in line:
            return line.strip(), True
            
    # Fallback to the whole text if 'boxed' is not found
    return solution_text, False


def evaluate_single_answer_with_llm(
    model_answer: str,
    ground_truth: str,
    api_manager: Any,
    config: Dict[str, Any],
    target_index: Optional[int] = None,
) -> EvaluationResult:
    """
    Evaluates a single model-generated answer against a ground truth using an LLM.
    This function constructs a prompt for an evaluator LLM, calls the API,
    and parses the response to determine if the model's answer is correct.
    It is designed to handle API errors and parsing failures gracefully.
    With ``ANSWER_BANK_ENABLED``, earlier verdicts for the same answer and
    simple rules decide first, and only the rest reach the LLM
    (see src/answer_bank.py).
    Args:
        model_answer (str): The solution text generated by the pipeline.
        ground_truth (str): The correct solution text.
        api_manager (Any): The instantiated API manager (Gemini or AvalAI).
        config (Dict[str, Any]): The global configuration dictionary.

    Returns:
        EvaluationResult: A dictionary containing the correctness (bool), a status
                          string, and any error details from the API.
    """
    # Guard clause: An empty or invalid answer is a distinct failure type.
    if not model_answer or not isinstance(model_answer, str):
        return {"is_correct": None, "status": "EMPTY_ANSWER", "error_details": None}

    if config.get("ANSWER_BANK_ENABLED", False) and isinstance(ground_truth, str) and ground_truth.strip():
        return _evaluate_with_answer_bank(model_answer, ground_truth, api_manager, config)

    target_benchmark = benchmark_name_for_target_index(config, target_index)
    has_exact_final_answers = uses_exact_final_answers(target_benchmark)

    if has_exact_final_answers:
        # MATH-500 and AIME expose a dedicated final-answer field. Always compare
        # it directly; boxed-line parsing is only for solution/rationale fields.
        template_name = "evaluator_v2"
    else:
        # For datasets with CoT + final answer (e.g. NuminaMath, GSM8K)
        if config.get("EVAL_PARSE_BOXED_GROUND_TRUTH", False):
            ground_truth, parse_success = _extract_last_boxed_line(ground_truth)
        else:
            parse_success = False

        if parse_success:
            template_name = "evaluator_v2"
        else:
            template_name = "evaluator_v1"

    return _call_llm_judge(model_answer, ground_truth, template_name, api_manager, config)[0]


def _unwrap_response(response: Any) -> Dict[str, Any]:
    """Unpack unexpected lists returned by API providers."""
    while isinstance(response, list):
        response = response[0] if len(response) > 0 else {"status": "FAILURE", "error_message": "Empty list returned"}
    if not isinstance(response, dict):
        response = {"status": "FAILURE", "error_message": f"Unexpected type: {type(response)}"}
    return response


def _call_llm_judge(
    model_answer: str,
    ground_truth: str,
    template_name: str,
    api_manager: Any,
    config: Dict[str, Any],
) -> Tuple[EvaluationResult, str]:
    """Make one evaluator call; return its result and the judge's raw reply."""
    logger = logging.getLogger(__name__)

    # MODIFIED: Determine which LLM model to use based on the type of the active manager
    evaluator_model = model_name_for(api_manager, config, "evaluator")

    evaluator_temp = config['DEFAULT_EVALUATOR_TEMPERATURE']

    # Lazy import to avoid circular dependencies
    from src.prompts import create_evaluation_prompt
    prompt = create_evaluation_prompt(model_answer, ground_truth, config, template_name=template_name)

    # print(f"      [API Context] Calling LLM for: Evaluation")
    response = _unwrap_response(api_manager.generate_content(
        prompt, evaluator_model, evaluator_temp, avalai_role="evaluator"
    ))

    # Handle API call failures
    if response.get('status') != 'SUCCESS':
        error_msg = response.get('error_message', 'Unknown API failure')
        logger.warning(f"LLM evaluation API call failed with status '{response.get('status')}': {error_msg}")
        return {"is_correct": None, "status": f"API_{response.get('status')}", "error_details": response}, ""

    # Handle successful API call, but potentially malformed response
    raw_text = response.get('text', '').strip()
    logger.debug(f"Evaluator raw response: '{raw_text}'")

    # Parse the 'Evaluation: [true/false]' line from the response
    eval_match = re.search(r"Evaluation:\s*(true|false)", raw_text, re.IGNORECASE)
    if eval_match:
        result_str = eval_match.group(1).lower()
        # logger.info(f"Parsed evaluation result: {result_str}")
        return {"is_correct": result_str == 'true', "status": "SUCCESS", "error_details": None}, raw_text
    else:
        logger.warning("Could not parse 'Evaluation:' line from LLM response. Treating as parsing failure.")
        return {"is_correct": None, "status": "PARSING_FAILED", "error_details": None}, raw_text


# --- Answer bank (see src/answer_bank.py) ---

_JUDGE_EXTRACTION = re.compile(r"Extracted Model (?:Final )?Answer:\s*(.+)", re.IGNORECASE)
# Verdicts not made by the ordinary prompt on this exact output; ANSWER_BANK_AUDIT_RATE
# of them are re-judged by it.
_AUDITED_METHODS = frozenset({"bank", "bank_value", "exact", "numeric", "llm_packed", "llm_joined"})


def _evaluate_with_answer_bank(
    model_answer: str, ground_truth: str, api_manager: Any, config: Dict[str, Any]
) -> EvaluationResult:
    """Decide from the bank or the rules when possible; otherwise ask the LLM judge."""
    bank = get_answer_bank(config)
    case = build_case(model_answer, ground_truth)
    judge_model = model_name_for(api_manager, config, "evaluator")
    temperature = config["DEFAULT_EVALUATOR_TEMPERATURE"]

    with PACKED_JUDGE.active():
        verdict, method = _known_verdict(bank, case)
        if verdict is not None:
            result = {"is_correct": verdict, "status": "SUCCESS", "error_details": None, "judge_method": method}
        else:
            result = PACKED_JUDGE.judge(
                case,
                single=lambda c: _bank_single_judge(c, model_answer, ground_truth, api_manager, config, bank, "llm"),
                pack=lambda cases: _bank_packed_judge(cases, api_manager, judge_model, temperature, bank),
                batch_key=(id(api_manager), judge_model, temperature),
                max_items=int(config.get("ANSWER_JUDGE_PACK_MAX_ITEMS", 1)),
                collect_seconds=float(config.get("ANSWER_JUDGE_PACK_COLLECT_SECONDS", 2.0)),
            )

        method = result.get("judge_method")
        if method in _AUDITED_METHODS and _needs_llm_check(bank, case, method, config):
            checked, _ = _bank_single_judge(case, model_answer, ground_truth, api_manager, config, bank, "audit")
            if checked["status"] == "SUCCESS":
                if checked["is_correct"] != result["is_correct"]:
                    logging.getLogger(__name__).warning(
                        "The LLM judge disagreed with the %s verdict for answer %r against %r; "
                        "using the judge's verdict.", method, case.raw_answer, case.gt_answer,
                    )
                result = checked
        bank.count(result.get("judge_method") or result["status"])
        return result


def _known_verdict(bank: AnswerBank, case: JudgeCase) -> Tuple[Optional[bool], Optional[str]]:
    """The bank's or the rules' verdict, or (None, None) when the judge must decide."""
    keys = [(case.key, "bank"), (case.text_key, "bank_text")] if case.answer is not None else [(case.text_key, "bank_text")]
    for key, method in keys:
        if bank.conflicted(case.scope, key):
            return None, None
        verdict = bank.lookup(case.scope, key)
        if verdict is not None:
            return verdict, method
    verdict, method = rule_verdict(case)
    if verdict is None and case.answer is not None:
        verdict = bank.value_verdict(case.scope, case.answer)
        method = "bank_value" if verdict is not None else None
    return verdict, method


def _needs_llm_check(bank: AnswerBank, case: JudgeCase, method: str, config: Dict[str, Any]) -> bool:
    """Audit a fixed share of verdicts, and re-judge heavily reused bank answers once."""
    rate = float(config.get("ANSWER_BANK_AUDIT_RATE", 0.0))
    # Deterministic per output, so a resumed run audits the same outputs.
    draw = int(hashlib.sha256((case.scope + case.text_key).encode("utf-8")).hexdigest()[:8], 16) / 2 ** 32
    if draw < rate:
        return True
    threshold = int(config.get("ANSWER_BANK_RECHECK_HITS", 0))
    return method == "bank" and threshold > 0 and bank.take_recheck(case.scope, case.key, threshold)


def _bank_verdict(
    bank: AnswerBank, case: JudgeCase, verdict: bool, judge_answer: Optional[str], method: str, judge_model: str
) -> bool:
    """Bank an LLM verdict; return whether it also holds for other outputs with this answer.

    The answer key is stored only when the judge read the same final answer we
    extracted; otherwise only this exact output text is reused.
    """
    keys = [case.text_key]
    shared = case.answer is None or same_answer(judge_answer, case.raw_answer)
    if case.answer is not None and shared:
        keys.append(case.key)
    bank.record(
        case.scope, keys, verdict,
        method=method, judge=judge_model, answer=case.raw_answer, judge_answer=judge_answer,
    )
    return shared


def _bank_single_judge(
    case: JudgeCase,
    model_answer: str,
    ground_truth: str,
    api_manager: Any,
    config: Dict[str, Any],
    bank: AnswerBank,
    method: str,
) -> Tuple[EvaluationResult, bool]:
    """One ordinary judge call, banked.

    The judge compares with the ground truth's own final answer when it has one,
    and with the whole ground truth otherwise; the choice no longer depends on
    the target benchmark, which judged retrieved Numina examples of MATH-500 and
    AIME runs against their whole solution as if it were a bare answer.
    """
    if case.gt_answer is not None:
        result, raw_text = _call_llm_judge(model_answer, case.gt_answer, "evaluator_v2", api_manager, config)
    else:
        result, raw_text = _call_llm_judge(model_answer, ground_truth, "evaluator_v1", api_manager, config)
    if result["status"] != "SUCCESS":
        return result, False
    match = _JUDGE_EXTRACTION.search(raw_text)
    judge_answer = match.group(1).strip().strip("*").strip() if match else None
    judge_model = model_name_for(api_manager, config, "evaluator")
    shared = _bank_verdict(bank, case, result["is_correct"], judge_answer, method, judge_model)
    return {**result, "judge_method": method}, shared


def _bank_packed_judge(
    cases: List[JudgeCase], api_manager: Any, judge_model: str, temperature: float, bank: AnswerBank
) -> List[Optional[Tuple[EvaluationResult, bool]]]:
    """Judge several answers in one call; None for any item the reply does not settle."""
    from src.prompts import create_packed_evaluation_prompt
    prompt = create_packed_evaluation_prompt([(case.tail, case.gt_answer) for case in cases])
    response = _unwrap_response(api_manager.generate_content(
        prompt, judge_model, temperature, avalai_role="evaluator"
    ))
    if response.get("status") != "SUCCESS":
        return [None] * len(cases)
    outcomes = []
    for case, item in zip(cases, parse_packed_reply(response.get("text", ""), len(cases))):
        # A judge that read another answer than ours sends the item to its own call.
        if item is None or not same_answer(item[0], case.raw_answer):
            outcomes.append(None)
            continue
        _bank_verdict(bank, case, item[1], item[0], "llm_packed", judge_model)
        outcomes.append(({"is_correct": item[1], "status": "SUCCESS", "error_details": None,
                          "judge_method": "llm_packed"}, True))
    return outcomes


def analyze_experiment_logs(
    all_experiments_logs: Dict[str, List[Dict]],
    ground_truths: List[str],
    api_managers: Dict[str, Any],
    config: Dict[str, Any]
) -> pd.DataFrame:
    """
    Analyzes all experiment logs, performs evaluations, and calculates Pass@K metrics.
    UPDATED: Now fully supports **Multi-Strategy Benchmarking**. 
    It iterates through:
    1. The primary solution strategy.
    2. Track A Benchmarks (Group Consistency from 'benchmarks' key).
    3. Track B Validations (Filter branches from 'steps_alternatives' key).
    
    It reports Pass@K metrics for *each* strategy independently in the final DataFrame.
    """
    logger = logging.getLogger(__name__)
    logger.info("Starting comprehensive analysis of all experiment logs.")
    analysis_summary = []

    # Get the standard reporting values, but note that Benchmarking tracks might
    # have their own specific N (e.g. 10), so we will need to handle K values dynamically.
    global_pass_k_values = config.get("PASS_K_VALUES_TO_REPORT", [1])
    results_dir = config['RESULTS_DIR']

    for exp_name, query_logs in all_experiments_logs.items():
        logger.info(f"--- Analyzing Experiment: {exp_name} ---")
        if not query_logs:
            logger.warning(f"No logs found for experiment '{exp_name}'. Skipping.")
            continue

        # UPDATE: New run logs persist provider routing in config_flags_used.
        # Merge it here so experiment-level evaluator overrides remain consistent
        # during post-run analysis; old logs safely fall back to global config.
        experiment_config = config.copy()
        logged_config = query_logs[0].get("config_flags_used", {})
        if isinstance(logged_config, dict):
            experiment_config.update(logged_config)
        
        # --- Phase 1: State Management & Resumption ---
        eval_file_path = os.path.join(results_dir, f"{exp_name}_detailed_eval.json")
        detailed_evaluations = load_json(eval_file_path) or []
        
        # Map existing evaluations by (hard_list_idx, strategy_name)
        # Old format logs might not have 'strategy', assume 'primary'
        evaluated_map = {} 
        for eval_log in detailed_evaluations:
            idx = eval_log['hard_list_idx']
            strat = eval_log.get('strategy', 'primary')
            evaluated_map[(idx, strat)] = eval_log

        logger.info(f"Loaded {len(detailed_evaluations)} existing evaluation entries for '{exp_name}'.")

        # Phase 2: Process Logs (Detecting Strategies)
        provider_for_eval = experiment_config.get('API_PROVIDER_EVALUATOR', 'gemini')
        manager_for_eval = api_managers[provider_for_eval]

        # 1. Gather all tasks that need evaluation
        tasks_to_run = []
        for log in query_logs:
            hard_list_idx = log["target_query_original_hard_list_idx"]
            ground_truth = ground_truths[hard_list_idx]
            
            strategies_to_evaluate = {}
            # A. Primary Strategy
            primary_attempts = log.get("steps", {}).get("solving", {}).get("solution_attempts", [])
            if primary_attempts: strategies_to_evaluate['primary'] = primary_attempts
            
            # B. Track A: Benchmarks
            benchmarks = log.get("benchmarks", {})
            for strat_name, result_data in benchmarks.items():
                attempts = result_data.get("solution_attempts", [])
                if attempts: strategies_to_evaluate[strat_name] = attempts

            # C. Track B: Validations & Alternatives
            alternatives = log.get("steps_alternatives", {})
            for strat_name, strat_data in alternatives.items():
                alt_attempts = strat_data.get("solving", {}).get("solution_attempts", [])
                if alt_attempts: strategies_to_evaluate[strat_name] = alt_attempts

            for strat_name, attempts in strategies_to_evaluate.items():
                if (hard_list_idx, strat_name) not in evaluated_map:
                    tasks_to_run.append({
                        "hard_list_idx": hard_list_idx,
                        "strat_name": strat_name,
                        "attempts": attempts,
                        "ground_truth": ground_truth
                    })

        # 2. Execute Evaluations in Parallel
        if tasks_to_run:
            from concurrent.futures import ThreadPoolExecutor, as_completed
            max_workers = experiment_config.get("BATCH_MAX_WORKERS", 5)
            
            def eval_worker(task):
                from src.context_logger import pipeline_context
                
                with pipeline_context(query_idx=task["hard_list_idx"], batch_id="evaluation"):
                    is_correct_list, status_list, error_details_list, method_list = [], [], [], []
                    # Pass@K only reads prefixes (any(is_correct_list[:k])), so the
                    # attempts after the first correct one cannot change any value.
                    lazy = experiment_config.get("EVAL_LAZY_PASS_AT_K", False)
                    for attempt in task["attempts"]:
                        if isinstance(attempt, str) and lazy and True in is_correct_list:
                            is_correct_list.append(None)
                            status_list.append(LAZY_SKIP_STATUS)
                            error_details_list.append(None)
                            method_list.append(None)
                        elif isinstance(attempt, str):
                            eval_result = evaluate_single_answer_with_llm(
                                attempt,
                                task["ground_truth"],
                                manager_for_eval,
                                experiment_config,
                                target_index=task["hard_list_idx"],
                            )
                            is_correct_list.append(eval_result["is_correct"])
                            status_list.append(eval_result["status"])
                            error_details_list.append(eval_result["error_details"])
                            method_list.append(eval_result.get("judge_method", "llm") if eval_result["status"] == "SUCCESS" else None)
                        elif isinstance(attempt, dict) and attempt.get('status') == 'FAILURE':
                            is_correct_list.append(None)
                            status_list.append("GENERATION_FAILED")
                            error_details_list.append(attempt.get("error_info"))
                            method_list.append(None)
                        else:
                            is_correct_list.append(None)
                            status_list.append("INVALID_ATTEMPT_FORMAT")
                            error_details_list.append(None)
                            method_list.append(None)

                    return {
                        "hard_list_idx": task["hard_list_idx"],
                        "strategy": task["strat_name"],
                        "is_correct_list": is_correct_list,
                        "evaluation_status_list": status_list,
                        "evaluation_error_details": error_details_list,
                        "evaluation_method_list": method_list,
                        "attempts": task["attempts"]
                    }

            # Run with a progress bar!
            with ThreadPoolExecutor(max_workers=max_workers) as executor:
                futures = [executor.submit(eval_worker, task) for task in tasks_to_run]
                for future in tqdm(as_completed(futures), total=len(futures), desc=f"Evaluating {exp_name}"):
                    eval_entry = future.result()
                    detailed_evaluations.append(eval_entry)
                    evaluated_map[(eval_entry["hard_list_idx"], eval_entry["strategy"])] = eval_entry
            
            # Final save after all tasks complete
            save_json(detailed_evaluations, eval_file_path)
            if experiment_config.get("ANSWER_BANK_ENABLED", False):
                logger.info(f"Answer bank decisions so far this session: {answer_bank_summary(experiment_config)}")

        # Phase 3: Aggregate Results (Per Strategy)
        # We need to collect all possible K values encountered in this run to normalize reporting
        all_encountered_k = set(global_pass_k_values)
        
        # Structure: metrics_by_strategy[strategy][metric] = count
        # We perform a first pass to find max N for each strategy to know which K's apply
        strategy_max_n = defaultdict(int)
        for eval_result in detailed_evaluations:
             strat = eval_result.get("strategy", "primary")
             n = len(eval_result.get("attempts", []))
             strategy_max_n[strat] = max(strategy_max_n[strat], n)
             if n > 0: all_encountered_k.add(n)

        sorted_k_values = sorted(list(all_encountered_k))

        metrics_by_strategy = defaultdict(lambda: {
            "pass_k_counts": {k: 0 for k in sorted_k_values},
            "error_counts": {"API_BLOCKED": 0, "API_ERROR": 0, "API_RATE_LIMITED": 0, "PARSING_FAILED": 0, "EMPTY_ANSWER": 0, "GENERATION_FAILED": 0},
            "total_valid": 0
        })

        for eval_result in detailed_evaluations:
            strat = eval_result.get("strategy", "primary")
            
            if eval_result.get("attempts"):
                metrics_by_strategy[strat]["total_valid"] += 1
                is_correct_list = eval_result["is_correct_list"]
                status_list = eval_result["evaluation_status_list"]

                # Tally errors
                for status in status_list:
                    error_key = status.replace("API_", "")
                    if error_key in metrics_by_strategy[strat]["error_counts"]:
                        metrics_by_strategy[strat]["error_counts"][error_key] += 1
                    elif status in metrics_by_strategy[strat]["error_counts"]:
                        metrics_by_strategy[strat]["error_counts"][status] += 1

                # Calculate Pass@K for all relevant K
                for k in sorted_k_values:
                    # Pass@K is valid if we have at least K attempts (or we treat missing as fail)
                    # For Benchmarking, we might have N=10, so Pass@1..Pass@10 are valid.
                    # For Validation, we have N=1, so only Pass@1 is valid.
                    
                    if len(is_correct_list) >= k:
                         if any(is_correct_list[:k]):
                             metrics_by_strategy[strat]["pass_k_counts"][k] += 1
                    else:
                         # Fallback: if we generated fewer than K attempts, check all available
                         # This implicitly handles "Pass@1" on an N=1 run even if we ask for Pass@5 
                         # (though semantically Pass@5 on N=1 is just Pass@1 or 0)
                         if any(is_correct_list):
                             metrics_by_strategy[strat]["pass_k_counts"][k] += 1
        
        # Phase 4: Compile Final Summary Row
        exp_summary = {
            "experiment_name": exp_name
        }
        
        # Flatten the metrics for the DataFrame
        for strat, data in metrics_by_strategy.items():
            suffix = "" if strat == "primary" else f"_{strat}"
            
            exp_summary[f"num_eval_{strat}"] = data["total_valid"]
            
            # Report Pass@K only for Ks that make sense for this strategy's N
            max_n = strategy_max_n[strat]
            
            for k in sorted_k_values:
                if k <= max_n or k in global_pass_k_values: # Always report globally requested Ks
                    col_name = f"pass@{k}{suffix}"
                    score = data["pass_k_counts"][k] / data["total_valid"] if data["total_valid"] > 0 else 0
                    exp_summary[col_name] = score
            
            for err_key, count in data["error_counts"].items():
                if count > 0: # Only report non-zero errors to keep table clean
                    col_name = f"errors_{err_key.lower()}{suffix}"
                    exp_summary[col_name] = count

        analysis_summary.append(exp_summary)
        
    logger.info("Finished analysis of all experiments.")
    
    analysis_df = pd.DataFrame(analysis_summary)
    
    return analysis_df
